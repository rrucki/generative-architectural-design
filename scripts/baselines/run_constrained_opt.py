"""
run_constrained_opt.py
----------------------
Baseline implementation using Scipy constrained non-linear optimization
(SLSQP - gradient-based and COBYLA - derivative-free) with multi-start initialization.

Evaluates performance on parcel instances generated by UrbanPlannerEnv.
"""

import argparse
import random
import sys
import time
from pathlib import Path
from typing import Dict, Any, List, Optional
import numpy as np
from scipy.optimize import minimize

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))
if str(PROJECT_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT / "src"))

from urban_planner.config import WINDOW_WIDTH, WINDOW_HEIGHT
from scripts.baselines.objective import calculate_footprint_cost, evaluate_final_solution


def generate_initial_guesses(
    permitted_poly: Any,
    num_guesses: int = 5,
    seed: Optional[int] = None,
) -> List[np.ndarray]:
    """
    Generates 8-DOF initial quadrilateral guesses in the canvas domain [0, W] x [0, H]
    matching the initial state distribution faced by the RL agent:
    - Start 0: Environment initial canvas outline [(0,0), (W,0), (W,H), (0,H)].
    - Starts 1..num_guesses-1: Random counter-clockwise 4-vertex quadrilaterals
      sampled across the canvas domain (without oracle centering on permitted_poly).
    """
    if seed is not None:
        np.random.seed(seed)

    guesses = []

    # 1. Start 0: Exact environment initial state (outer canvas corners)
    quad0 = np.array(
        [
            0.0, 0.0,
            float(WINDOW_WIDTH), 0.0,
            float(WINDOW_WIDTH), float(WINDOW_HEIGHT),
            0.0, float(WINDOW_HEIGHT),
        ],
        dtype=float,
    )
    guesses.append(quad0)

    # 2. Starts 1..num_guesses-1: Randomized 4-vertex CCW quadrilaterals in canvas space
    from scripts.baselines.objective import order_points_ccw
    for _ in range(num_guesses - 1):
        rcx = np.random.uniform(0.2 * WINDOW_WIDTH, 0.8 * WINDOW_WIDTH)
        rcy = np.random.uniform(0.2 * WINDOW_HEIGHT, 0.8 * WINDOW_HEIGHT)
        sub_w = np.random.uniform(150.0, 500.0)
        sub_h = np.random.uniform(150.0, 500.0)

        pts = [
            (
                np.clip(rcx + np.random.uniform(-0.5, 0.5) * sub_w, 0.0, float(WINDOW_WIDTH)),
                np.clip(rcy + np.random.uniform(-0.5, 0.5) * sub_h, 0.0, float(WINDOW_HEIGHT)),
            )
            for _ in range(4)
        ]
        pts_ccw = order_points_ccw(pts)
        guess = np.array([coord for pt in pts_ccw for coord in pt], dtype=float)
        guesses.append(guess)

    return guesses


def run_slsqp(
    raw_env: Any,
    seed: int,
    max_evals: int = 4000,
    num_starts: int = 5,
) -> Dict[str, Any]:
    """
    Runs multi-start SLSQP (Sequential Least Squares Programming) optimization on a parcel.
    """
    return run_scipy_minimize(raw_env, seed=seed, method="SLSQP", max_evals=max_evals, num_starts=num_starts)


def run_cobyla(
    raw_env: Any,
    seed: int,
    max_evals: int = 10000,
    num_starts: int = 10,
) -> Dict[str, Any]:
    """
    Runs multi-start COBYLA (Constrained Optimization BY Linear Approximation) optimization on a parcel.
    """
    return run_scipy_minimize(raw_env, seed=seed, method="COBYLA", max_evals=max_evals, num_starts=num_starts)


def run_scipy_minimize(
    raw_env: Any,
    seed: int,
    method: str = "SLSQP",
    max_evals: int = 10000,
    num_starts: int = 10,
) -> Dict[str, Any]:
    """
    Runs multi-start SciPy minimize optimization for a single parcel instance.
    """
    random.seed(seed)
    np.random.seed(seed)

    obs, info = raw_env.reset(seed=seed)
    unwrapped = raw_env.unwrapped

    permitted_poly = unwrapped.plot.permitted_outline
    initial_guesses = generate_initial_guesses(permitted_poly, num_guesses=num_starts, seed=seed)

    bounds = [(0.0, float(WINDOW_WIDTH)), (0.0, float(WINDOW_HEIGHT))] * 4

    total_fevals = 0
    best_x = initial_guesses[0]
    best_cost = float("inf")
    best_eval = None

    start_time = time.perf_counter()

    for idx, x0 in enumerate(initial_guesses):
        evals_in_run = 0

        def cost_func(x):
            nonlocal evals_in_run
            evals_in_run += 1
            return calculate_footprint_cost(x, unwrapped)

        max_iter_per_start = max(50, max_evals // num_starts)

        options = {"maxiter": max_iter_per_start}
        if method == "SLSQP":
            options["ftol"] = 1e-4
            res = minimize(
                cost_func,
                x0,
                method="SLSQP",
                bounds=bounds,
                options=options,
            )
        elif method == "COBYLA":
            options["tol"] = 1e-4
            res = minimize(
                cost_func,
                x0,
                method="COBYLA",
                options=options,
            )
        else:
            raise ValueError(f"Unsupported method: {method}")

        total_fevals += evals_in_run
        cand_x = res.x
        cand_cost = float(res.fun)

        eval_res = evaluate_final_solution(cand_x, unwrapped)

        if cand_cost < best_cost or (eval_res["solved"] and (best_eval is None or not best_eval["solved"])):
            best_cost = cand_cost
            best_x = np.copy(cand_x)
            best_eval = eval_res

        # Early exit if exact feasible solution found
        if best_eval is not None and best_eval["solved"]:
            break

        if total_fevals >= max_evals:
            break

    wall_clock_seconds = time.perf_counter() - start_time

    if best_eval is None:
        best_eval = evaluate_final_solution(best_x, unwrapped)

    best_eval["steps"] = total_fevals
    best_eval["wall_clock_seconds"] = wall_clock_seconds

    return best_eval


if __name__ == "__main__":
    import gymnasium as gym
    import urban_planner

    parser = argparse.ArgumentParser(description="Test SLSQP/COBYLA constrained optimization baseline")
    parser.add_argument("--method", type=str, default="slsqp", choices=["slsqp", "cobyla", "both"], help="Optimization method")
    parser.add_argument("--test-parcels", type=int, default=5, help="Number of test parcels")
    parser.add_argument("--seed", type=int, default=42, help="Starting random seed")
    parser.add_argument("--num-starts", type=int, default=10, help="Number of multi-start initializations")
    args = parser.parse_args()

    methods_to_test = ["slsqp", "cobyla"] if args.method == "both" else [args.method]
    raw_env = gym.make("UrbanPlanner-v0", stage=4)

    for m in methods_to_test:
        method_name = m.upper()
        print(f"\n--- Running {method_name} Baseline on {args.test_parcels} Parcels (Seed={args.seed}, Multi-start={args.num_starts}) ---")

        solved_count = 0
        total_time = 0.0
        total_evals = 0

        for i in range(args.test_parcels):
            p_seed = args.seed + i
            if m == "slsqp":
                result = run_slsqp(raw_env, seed=p_seed, num_starts=args.num_starts)
            else:
                result = run_cobyla(raw_env, seed=p_seed, num_starts=args.num_starts)

            if result["solved"]:
                solved_count += 1
            total_time += result["wall_clock_seconds"]
            total_evals += result["steps"]

            status = "SOLVED" if result["solved"] else "FAILED"
            print(
                f"Parcel {i+1} (Seed {p_seed}): [{status}] | "
                f"Evals: {result['steps']:5d} | "
                f"Time: {result['wall_clock_seconds']:.3f}s | "
                f"Area Err: {result['area_error']:.1f}% | "
                f"Width Feasible: {result['width_feasible']} | "
                f"Ortho Dev: {result['ortho_deviation']:.2f}°"
            )

        success_rate = (solved_count / args.test_parcels) * 100.0
        avg_time = total_time / args.test_parcels
        avg_evals = total_evals / args.test_parcels

        print(f"[{method_name} Summary] Feasibility: {success_rate:.1f}% ({solved_count}/{args.test_parcels}) | Mean Time: {avg_time:.3f}s | Mean Evals: {avg_evals:.1f}")

    print("\n Constrained optimization baselines test completed successfully.")
