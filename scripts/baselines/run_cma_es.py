"""
run_cma_es.py
-------------
Baseline implementation using Covariance Matrix Adaptation Evolution Strategy (CMA-ES)
for single-instance building footprint polygon optimization.

Evaluates performance on parcel instances generated by UrbanPlannerEnv.
"""

import argparse
import random
import sys
import time
from pathlib import Path
from typing import Dict, Any, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))
if str(PROJECT_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT / "src"))

import cma
import numpy as np

from urban_planner.config import WINDOW_WIDTH, WINDOW_HEIGHT
from scripts.baselines.objective import calculate_footprint_cost, evaluate_final_solution


def run_cma_es(
    raw_env: Any,
    seed: int,
    max_evals: int = 100000,
    ftol: float = 1e-4,
    popsize: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Runs CMA-ES optimization for a single parcel instance.

    Args:
        raw_env: The Gym environment instance (UrbanPlanner-v0)
        seed: Random seed for parcel generation and optimizer reproducibility
        max_evals: Maximum function evaluations budget
        ftol: Target cost threshold for early stopping (solution reached)
        popsize: Optional population size override

    Returns:
        Dict[str, Any] containing standard benchmark metrics:
        - solved (bool)
        - steps (int) -> total function evaluations
        - area_error (float)
        - violation_rate (float)
        - width_feasible (bool)
        - ortho_deviation (float)
        - wall_clock_seconds (float)
    """
    random.seed(seed)
    np.random.seed(seed)

    obs, info = raw_env.reset(seed=seed)
    unwrapped = raw_env.unwrapped

    permitted_poly = unwrapped.plot.permitted_outline
    minx, miny, maxx, maxy = permitted_poly.bounds
    cx, cy = (minx + maxx) / 2.0, (miny + maxy) / 2.0

    # Initial guess: small centered rectangle inside envelope
    w = max(50.0, min(150.0, (maxx - minx) * 0.35))
    h = max(50.0, min(150.0, (maxy - miny) * 0.35))
    x0 = np.array(
        [
            cx - w / 2.0, cy - h / 2.0,
            cx + w / 2.0, cy - h / 2.0,
            cx + w / 2.0, cy + h / 2.0,
            cx - w / 2.0, cy + h / 2.0,
        ],
        dtype=float,
    )

    sigma0 = max(15.0, 0.25 * min(maxx - minx, maxy - miny))

    # Coordinate bounds within screen space
    lower_bounds = [0.0] * 8
    upper_bounds = [float(WINDOW_WIDTH), float(WINDOW_HEIGHT)] * 4

    opts = {
        "bounds": [lower_bounds, upper_bounds],
        "seed": seed,
        "maxfevals": max_evals,
        "tolfun": ftol,
        "verb_disp": 0,
        "verbose": -9,
    }
    if popsize is not None:
        opts["popsize"] = popsize

    es = cma.CMAEvolutionStrategy(x0, sigma0, opts)

    start_time = time.perf_counter()
    fevals = 0
    best_x = x0
    best_cost = float("inf")

    early_stop = False
    while not es.stop() and not early_stop:
        solutions = es.ask()
        fitnesses = []
        for sol in solutions:
            cost = calculate_footprint_cost(sol, unwrapped)
            fitnesses.append(cost)
            fevals += 1

            if cost < best_cost:
                best_cost = cost
                best_x = np.copy(sol)

                # Check if exact solution criteria met in discrete assessment
                eval_check = evaluate_final_solution(sol, unwrapped)
                if eval_check["solved"]:
                    early_stop = True

            if fevals >= max_evals:
                early_stop = True

        es.tell(solutions, fitnesses)
        if early_stop:
            break

    wall_clock_seconds = time.perf_counter() - start_time

    # Final evaluation
    final_eval = evaluate_final_solution(best_x, unwrapped)
    final_eval["steps"] = fevals
    final_eval["wall_clock_seconds"] = wall_clock_seconds

    return final_eval


if __name__ == "__main__":
    import gymnasium as gym
    import urban_planner

    parser = argparse.ArgumentParser(description="Test CMA-ES baseline on parcel instances")
    parser.add_argument("--test-parcels", type=int, default=5, help="Number of test parcels")
    parser.add_argument("--seed", type=int, default=42, help="Starting random seed")
    parser.add_argument("--max-evals", type=int, default=50000, help="Max evaluations budget per parcel")
    args = parser.parse_args()

    print(f"--- Running CMA-ES Baseline on {args.test_parcels} Parcels (Seed={args.seed}) ---")
    raw_env = gym.make("UrbanPlanner-v0", stage=4)

    solved_count = 0
    total_time = 0.0
    total_evals = 0

    for i in range(args.test_parcels):
        p_seed = args.seed + i
        result = run_cma_es(raw_env, seed=p_seed, max_evals=args.max_evals)

        if result["solved"]:
            solved_count += 1
        total_time += result["wall_clock_seconds"]
        total_evals += result["steps"]

        status = "SOLVED" if result["solved"] else "FAILED"
        print(
            f"Parcel {i+1} (Seed {p_seed}): [{status}] | "
            f"Evals: {result['steps']:5d} | "
            f"Time: {result['wall_clock_seconds']:.3f}s | "
            f"Area Err: {result['area_error']:.1f}% | "
            f"Width Feasible: {result['width_feasible']} | "
            f"Ortho Dev: {result['ortho_deviation']:.2f}°"
        )

    success_rate = (solved_count / args.test_parcels) * 100.0
    avg_time = total_time / args.test_parcels
    avg_evals = total_evals / args.test_parcels

    print("\n--- Summary ---")
    print(f"Feasibility Rate: {success_rate:.1f}% ({solved_count}/{args.test_parcels})")
    print(f"Mean Time / Parcel: {avg_time:.3f}s")
    print(f"Mean Function Evals: {avg_evals:.1f}")
    print(" CMA-ES baseline test completed successfully.")
