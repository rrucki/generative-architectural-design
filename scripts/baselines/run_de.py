"""
run_de.py
---------
Baseline implementation using Differential Evolution (scipy.optimize.differential_evolution)
for global stochastic building footprint polygon optimization.

Evaluates performance on parcel instances generated by UrbanPlannerEnv.
"""

import argparse
import random
import sys
import time
from pathlib import Path
from typing import Dict, Any, Optional
import numpy as np
from scipy.optimize import differential_evolution

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))
if str(PROJECT_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT / "src"))

from urban_planner.config import WINDOW_WIDTH, WINDOW_HEIGHT
from scripts.baselines.objective import calculate_footprint_cost, evaluate_final_solution


def run_de(
    raw_env: Any,
    seed: int,
    max_evals: int = 100000,
    popsize: int = 20,
    maxiter: int = 500,
    tol: float = 1e-4,
    mutation: tuple = (0.5, 1.0),
    recombination: float = 0.7,
) -> Dict[str, Any]:
    """
    Runs Differential Evolution optimization for a single parcel instance.

    Args:
        raw_env: Gym environment instance (UrbanPlanner-v0)
        seed: Random seed for reproducibility
        max_evals: Maximum function evaluations budget
        popsize: Population multiplier (total population = popsize * len(x) = popsize * 8)
        maxiter: Maximum generations
        tol: Relative tolerance for convergence
        mutation: Mutation constant or tuple (min, max) for dithering
        recombination: Recombination/crossover probability

    Returns:
        Dict[str, Any] containing standard benchmark metrics:
        - solved (bool)
        - steps (int) -> total function evaluations
        - area_error (float)
        - violation_rate (float)
        - width_feasible (bool)
        - ortho_deviation (float)
        - wall_clock_seconds (float)
    """
    random.seed(seed)
    np.random.seed(seed)

    obs, info = raw_env.reset(seed=seed)
    unwrapped = raw_env.unwrapped

    permitted_poly = unwrapped.plot.permitted_outline
    minx, miny, maxx, maxy = permitted_poly.bounds
    margin = 50.0

    # Tight bounds around permitted envelope to guide global search
    bound_x = (max(0.0, minx - margin), min(float(WINDOW_WIDTH), maxx + margin))
    bound_y = (max(0.0, miny - margin), min(float(WINDOW_HEIGHT), maxy + margin))
    bounds = [bound_x, bound_y] * 4

    total_fevals = 0
    best_x = None
    best_cost = float("inf")
    solved_solution = None

    def cost_func(x):
        nonlocal total_fevals, best_cost, best_x, solved_solution
        total_fevals += 1
        cost = calculate_footprint_cost(x, unwrapped)
        if cost < best_cost:
            best_cost = cost
            best_x = np.copy(x)
            eval_res = evaluate_final_solution(x, unwrapped)
            if eval_res["solved"]:
                solved_solution = eval_res
        return cost

    def early_stop_callback(xk, convergence=None):
        nonlocal solved_solution
        if solved_solution is not None or total_fevals >= max_evals:
            return True
        eval_res = evaluate_final_solution(xk, unwrapped)
        if eval_res["solved"]:
            solved_solution = eval_res
            return True
        return False

    start_time = time.perf_counter()

    res = differential_evolution(
        cost_func,
        bounds=bounds,
        seed=seed,
        maxiter=maxiter,
        popsize=popsize,
        tol=tol,
        mutation=mutation,
        recombination=recombination,
        callback=early_stop_callback,
        workers=1,
        updating="deferred",
    )

    wall_clock_seconds = time.perf_counter() - start_time

    if solved_solution is not None:
        final_eval = solved_solution
    else:
        chosen_x = best_x if best_x is not None else res.x
        final_eval = evaluate_final_solution(chosen_x, unwrapped)

    final_eval["steps"] = total_fevals
    final_eval["wall_clock_seconds"] = wall_clock_seconds

    return final_eval


if __name__ == "__main__":
    import gymnasium as gym
    import urban_planner

    parser = argparse.ArgumentParser(description="Test Differential Evolution baseline on parcel instances")
    parser.add_argument("--test-parcels", type=int, default=5, help="Number of test parcels")
    parser.add_argument("--seed", type=int, default=42, help="Starting random seed")
    parser.add_argument("--max-evals", type=int, default=50000, help="Max evaluations budget per parcel")
    args = parser.parse_args()

    print(f"--- Running Differential Evolution Baseline on {args.test_parcels} Parcels (Seed={args.seed}) ---")
    raw_env = gym.make("UrbanPlanner-v0", stage=4)

    solved_count = 0
    total_time = 0.0
    total_evals = 0

    for i in range(args.test_parcels):
        p_seed = args.seed + i
        result = run_de(raw_env, seed=p_seed, max_evals=args.max_evals)

        if result["solved"]:
            solved_count += 1
        total_time += result["wall_clock_seconds"]
        total_evals += result["steps"]

        status = "SOLVED" if result["solved"] else "FAILED"
        print(
            f"Parcel {i+1} (Seed {p_seed}): [{status}] | "
            f"Evals: {result['steps']:5d} | "
            f"Time: {result['wall_clock_seconds']:.3f}s | "
            f"Area Err: {result['area_error']:.1f}% | "
            f"Width Feasible: {result['width_feasible']} | "
            f"Ortho Dev: {result['ortho_deviation']:.2f}°"
        )

    success_rate = (solved_count / args.test_parcels) * 100.0
    avg_time = total_time / args.test_parcels
    avg_evals = total_evals / args.test_parcels

    print("\n--- Summary ---")
    print(f"Feasibility Rate: {success_rate:.1f}% ({solved_count}/{args.test_parcels})")
    print(f"Mean Time / Parcel: {avg_time:.3f}s")
    print(f"Mean Function Evals: {avg_evals:.1f}")
    print(" Differential Evolution baseline test completed successfully.")
